import numpy as np
from sklearn.decomposition import PCA
from pcipy.pci_filter import PCIFilter
from pcipy.filter import LinearFilter
from pcipy.data import TimeData

# The pci_filter.PCIfilter class can be considered to be a bells-and-whistles pci constructor suitable for developmental
# experiements. The class defined here is intended to be the more applied practical interface going forward, and like
# tdi_filter,  specifically adapted to work with LISA-formatted data. It is currently
# built atop the PCIFilter functionality, but a cleaned up future version might separate the two.
class LocalPCIFilter(LinearFilter):
    
    
    def __init__(self, measurements_data, eval_time=None, in_chans=['sci'], data_t0=0, skip_secs=0, nhalf=45, pci_regard_hours=12, pci_order=1, n_compts=6, Tscale=1, sort_by_rms=False, verbose=False, testPCI=False): 

        '''
        This class provides simplified interface to the PCIFilter which conforms to the LinearFilter class interface
        and which is, in particular, suitable for LISAinstrument data and with PiecewiseFilter.

        It applies the PCI filter class temporarily to built the stencil but does not retain it for later reference.
        Regardless of the PCI order used in filter development, the resulting filter will be time-independent, keeping
        essentially just the PCI-0 part.

        Parameters
        ----------
        measurements_data : pytdi.Data
            This should contain the simulated LISA data needed for the analysis
        eval_time : Central time for the analysis. The realized filter will be a filter best suited to this time. Default is half the regard period from the start of the data.
        in_chans : List of str
            List of which types of input channels to include as filter inputs
        data_t0 : float, optional
            Reference time corresponding to the first sample in the full_data (before skip). Default is 0.
        skip_secs : float, optional
            If this is set, the first skip_secs of the data will be not be included in the analysis.
        nhalf : int, optional
            Filter stencil halfwidth. The default is 45.
        pci_regard_hours : To support piecewise filtering, we make a distinction between the range of data which is supplied as input overall, and the range which is regarded in the PCI filter construction process.  The process will include the data half this value forward and backward from the eval_time, truncating at the edge of data if needed. Default is 12 hours.
        pci_order : Order of time polynomials used in constructing the pci_filter, though the resulting filter will be order 0..
        n_compts : int, optional
            PCA results will be truncated to this length after initial processing. The default is 6.
        Tscale : int, optional
            Time-scale used for weighting time-polynomial terms with order>0. Default 1.
        sort_by_rms : bool, optional
            Whether to select the channels by RMS (vs variance). Default False
        detrend

        Returns
        -------
        None.        
        
        The input channels are stretches of data, usually of length ns+2*nhalf, but sometimes varying. The variations are:
          : (full length of matrix)
          0:ns_fixed
          0:ns+2*nhalf
          skip:skip+ns+2*nhalf
        In every case the window is trivial np.ones([data lenght])  

        '''
        '''
        ...FIXME Is there anything from this TDI descriptor that we want to add here?  FIXME...
        This class realizes a constant LinearFilter based on a deduced TDI stencil.  

        The stencil is computed from a measurements data file as generated by LISAInstrument. 
        Information in that file is used with pytdi to compute reverse engineer the defacto TDI 
        operation applied at a reference point in the data stream.  The output channels are TDI2 
        X, Y and Z.

        Parameters
        ----------
        measurements_data: pytdi.Data
            This should be a Data structure from pytdi for instrument simulation data
        eval_time: float
            This is the time point in the (output) data stream for which the TDI kernel should
            be estimated. By default, t0=None, and t0 is set to the earliest point which is 
            supported.
        nleft: int
            The number of points that TDI response should be searched for to the left of the
            input-stream point.
        nright: int
            The number of points that TDI response should be searched for to the right of the
            input-stream point.
        in_chans: list
            This is the list of which pytdi data channel types to include in the TDI kernel computation.
            The default is ['isi'] which uses only the inter-spacecraft interferometer. To use all
            18 central phasemeter channels set to ['isi','rfi','tmi'].
        method: string
            This determines the method for estimating the TDI kernel. Default is 'simple' which
            estimates via pytdi impluse response, ignoring the small amount of variation in the
            response across the kernel width.  The 'exact' treatment is quite slow (minutes) but
            computes the impulse response exactly for each kernel coefficient.  The compromise
            'linear' treatment computes the the exact impulse response at the times corresponding
            to the kernel start and end, but linearly interpolates the interior coefficients.  
            Each method begins with the simple treatment to determine the kernel extent. 
        '''

        # PCI construction
        self.n_output_channels=n_compts
        
        #    Preprocess the measurements data
        fs = measurements_data.fs
        iskip = int(skip_secs*fs)
        print('iskip=',iskip)
        self.in_chans=in_chans
        self.mosas_order = ['12', '23', '31', '13', '21', '32']
        in_names=[]
        for chan in in_chans:
            for link in self.mosas_order:
                in_names.append(f'{chan}_{link}')
        self.input_names=in_names
        self.n_input_channels=len(in_names)
        
        self.dt=1/measurements_data.fs

        #    Prepare measurements data subset:
        data_ns = next(iter(measurements_data.measurements.values())).shape[0]
        pci_ns = int(pci_regard_hours*3600*fs)
        if eval_time is None:
            ieval = pci_ns//2 + nhalf   
        else:
            ieval = int((eval_time-data_t0)*fs+0.5)
        i0 = ieval - pci_ns//2 - nhalf

        #    Range checks and adjustments
        print('prelim ieval,i0,pci_ns,data_ns:',ieval,i0,pci_ns,data_ns)
        if i0<0:
                pci_ns -= -i0
                i0 = 0
        if i0 + pci_ns > data_ns -iskip -2*nhalf: pci_ns = data_ns -iskip -2*nhalf -i0
    
        print('final i0,pci_ns,data_ns:',i0,pci_ns,data_ns)
        
                
        #       Note that in the next line we are taking the data as raw freq data rather than fractional freq.
        #       This should not matter for pci, as long as we are consistent with the data to be filtered
        y_list = [measurements_data.measurements[name] for name in in_names]

        #       The procedure here may be overly complex.  We for the type of data-structures used by filter.py
        #       although so far PCIFilter doesn't use them so we then disregard them.  The right approach is
        #       TBD.  FIXME
        #       create a TimeData object covering the desired range
        y_data = TimeData(np.array(y_list, dtype=np.float64)[:, iskip:],
                          dt=1/fs,
                          t0=iskip/fs,
                          names=in_names)
        y_data_pci = y_data.get_range(i0,i0+pci_ns+2*nhalf)
        
        #    Construct the PCI filter
        pci_ref_t0 = data_t0 + i0/fs
        print('check t0:',pci_ref_t0,y_data_pci.t0)        
        pci = PCIFilter(y_data_pci.data, fs, nhalf=nhalf, order=pci_order, maxcompts=n_compts, t0=eval_time, sort_by_rms=sort_by_rms, Tscale=Tscale, ref_t0=None, verbose=verbose)

        if testPCI: self.pci_TEST=pci #This is just here for temporary debugging test

        #    Extract the PCI-0 equivalent kernel evaluated at the reference time.
        #pci_stencil_compts = pci.stencil_compts[:,0,:]#This just takes the PCI part and works precisely at the 0 time. This was tested to work with PCI-0
        pci_stencil_compts = pci.stencil_at_time(eval_time)#This allows a time that is different from the 0 time which may not be guaranteed to be eval_time by construction.
        self.kernel_compts = pci.stencil_compts[:,0,:].reshape(n_compts,1+2*nhalf,self.n_input_channels)[:,::-1,:]
        
        self.nright = nhalf
        self.nleft = nhalf
        
        # In this case, because the above compute_kernel_from_measurements function takes input
        # data from i0, which is applied to produce output TDI data ranging from i0-nleft to i0+nright,
        # we take the middle point of that range as the time-reference point.  TBD is to modify
        # the compute_kernel function to be fully consistent with output at i0 in the output stream.
        # Then we should also ensure that kernel_ref_time= t0
        #self.kernel_ref_time =  ( i0 - ( self.nright - self.nleft ) // 2 ) * self.dt
        #This should work if the pci_filter time-dependence is working as expected
        self.kernel_ref_time = eval_time
        #self.kernel_compts=kernel#np.transpose(kernel,[0,2,1])
        #print('Constructed TDI kernel of shape',self.kernel_compts.shape,' and set nleft and nright to:',self.nleft, self.nright)
        self.constant_kernel=True

        self.output_names = None
        
